// QA de navegador: seção "Meu jeito de escrever" (Configurações > Atendente). Fixture isolado; nada real.
import fs from 'node:fs';
import { chromium } from 'playwright-core';
const results = []; const issues = [];
const check = (name, ok, detail = '') => { results.push({ name, ok: !!ok, detail }); console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${detail ? '  — ' + detail : ''}`); };
const browser = await chromium.launch({ executablePath: 'C:/Users/User/AppData/Local/ms-playwright/chromium-1248/chrome-win64/chrome.exe', headless: true });
const page = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
page.on('console', (m) => { if (m.type() === 'error') issues.push(m.text()); }); page.on('pageerror', (e) => issues.push(e.message));
await page.goto('http://127.0.0.1:3355/mensageiro/');
await page.fill('input[type=email]', 'qa@example.test'); await page.fill('input[type=password]', 'qa-only');
await page.getByRole('button', { name: 'Entrar no Mensageiro' }).click();
await page.getByText(/99999-0001/).first().waitFor({ timeout: 10000 });
await page.getByRole('button', { name: /Configurações/ }).first().click();
await page.getByRole('tab', { name: /Atendente/ }).click().catch(async () => { await page.getByText('Atendente', { exact: true }).first().click(); });
await page.getByText('Meu jeito de escrever').waitFor({ timeout: 10000 });
check('S1 seção "Meu jeito de escrever" aparece com o aviso de privacidade', /enviadas ao modelo como exemplos/.test(await page.locator('section', { hasText: 'Meu jeito de escrever' }).innerText()));
await page.getByRole('button', { name: /Buscar exemplos/ }).click();
await page.locator('section', { hasText: 'Meu jeito de escrever' }).locator('input[type=checkbox]').first().waitFor({ timeout: 10000 });
const labels = await page.locator('section', { hasText: 'Meu jeito de escrever' }).locator('li').allInnerTexts();
check('S2 só aparecem frases limpas (sem número, link, nome nem jeito de robô)', labels.length > 0 && labels.every((t) => !/\d|https?:|@|Como posso ajudar/.test(t)), JSON.stringify(labels));
await page.locator('section', { hasText: 'Meu jeito de escrever' }).locator('input[type=checkbox]').first().check();
await page.getByRole('button', { name: 'Salvar exemplos' }).click();
await page.getByText(/exemplo\(s\) salvo\(s\)/).waitFor({ timeout: 8000 });
const saved = await fetch('http://127.0.0.1:3355/mensageiro/api/copilot/style-samples', { headers: { Authorization: 'Bearer qa-admin' } }).then((r) => r.json());
check('S3 salvar grava só as escolhidas no servidor', saved.samples.length === 1 && saved.samples[0] === labels[0], JSON.stringify(saved));
await page.screenshot({ path: 'shot-style.png' });
check('S99 console limpo', issues.length === 0, issues.slice(0, 3).join(' || '));
await browser.close();
fs.writeFileSync('e2e-style-results.json', JSON.stringify({ results, issues }, null, 2));
process.exit(results.some((r) => !r.ok) ? 1 : 0);
